"""
RockTranslate — generates assets/ui/js/icons.js from Lucide (ISC licence).

Only the icons the UI uses are embedded (offline app, no font, no CDN).

    npm pack lucide-static && tar -xzf lucide-static-*.tgz
    python dev_tools/gen_icons.py package/icons

Add a name to ICONS (a file name of lucide-static/icons without .svg), run
again, then use it with data-icon="name" or RT_ICON('name').
"""

import json
import os
import re
import sys

ICONS = sorted(set("""
activity book-a book-open bot circle-x clipboard-paste columns-2 command copy download eraser expand file
file-down file-output file-text files folder-open git-branch globe highlighter history image image-plus info
key-round keyboard languages lightbulb link list-tree loader-circle log-out message-circle
message-circle-question messages-square mic mic-off monitor-cog moon mouse-pointer-2 notebook-pen panel-right
pencil printer quote refresh-cw repeat rotate-ccw rotate-cw scan search send settings sliders-horizontal square
square-stop sun-moon trash trash-2 type user volume-2 x zoom-in zoom-out bug
""".split()))


def main(folder: str) -> None:
    icons = {}
    version = ""
    for name in ICONS:
        with open(os.path.join(folder, name + ".svg"), encoding="utf-8") as f:
            svg = f.read()
        version = version or (re.search(r"lucide-static v([\d.]+)", svg) or [None, ""])[1]
        inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
        icons[name] = re.sub(r"\s+", " ", inner).replace("> <", "><").strip()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "rocktranslate", "assets", "ui", "js",
                       "icons.js")
    body = json.dumps(icons, indent=1, ensure_ascii=False)
    with open(out, "w", encoding="utf-8") as f:
        f.write(f"""/**
 * RockTranslate — UI icons (generated by dev_tools/gen_icons.py, do not edit).
 * Icons: Lucide v{version} — https://lucide.dev — ISC License,
 * Copyright (c) Lucide Icons and Contributors.
 *
 *   <span data-icon="languages"></span>    filled automatically (also when added later)
 *   RT_ICON('languages')                   the <svg> markup, for code that builds HTML
 */
(function () {{
    const ICONS = {body};

    window.RT_ICON = function (name, extraClass) {{
        const inner = ICONS[name];
        if (!inner) return '';
        return '<svg class="rt-svg' + (extraClass ? ' ' + extraClass : '') + '" viewBox="0 0 24 24" fill="none" ' +
            'stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">' +
            inner + '</svg>';
    }};

    function fill(root) {{
        (root.querySelectorAll ? root.querySelectorAll('[data-icon]') : []).forEach((el) => {{
            if (el.dataset.iconDone === el.dataset.icon) return;
            el.innerHTML = window.RT_ICON(el.dataset.icon);
            el.dataset.iconDone = el.dataset.icon;
        }});
    }}
    window.RT_FILL_ICONS = fill;
    const start = () => {{
        fill(document);
        new MutationObserver((records) => records.forEach((r) => {{
            if (r.type === 'attributes') fill(r.target.parentNode || document);
            r.addedNodes.forEach((n) => {{ if (n.nodeType === 1) {{ if (n.dataset && n.dataset.icon) fill(n.parentNode); fill(n); }} }});
        }})).observe(document.documentElement, {{ childList: true, subtree: true, attributes: true, attributeFilter: ['data-icon'] }});
    }};
    if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', start); else start();
}})();
""")
    print(f"{len(icons)} icons -> {os.path.normpath(out)}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "package/icons")
