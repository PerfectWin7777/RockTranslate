        translate(key, variables = {}) {
            let text = this.translations[this.locale]?.[key] || this.translations['en']?.[key] || key;
            for (const [vKey, vVal] of Object.entries(variables)) {
                text = text.replace(`{${vKey}}`, vVal);
            }
            return text;
        },

